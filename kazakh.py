"""Казахские команды для KAR.

Казахский язык — SOV: объект стоит перед глаголом («ютубты аш» = «открой ютуб»), а у слов есть
падежные окончания. Поэтому вместо дублирования всей таблицы команд здесь делается разбор фразы на
объект и глагол, и она превращается в каноническую русскую команду, которую уже понимает actions.py.

Весь разбор идёт по «свёрнутому» тексту: специфические казахские буквы заменены на близкие русские
(ә→а, ғ→г, қ→к, ң→н, ө→о, ұ/ү→у, һ→х, і→и). Так фраза находится, даже если распознавание
записало букву иначе (частая ошибка Vosk и Google).
"""
import re

_FOLD = str.maketrans({"ә": "а", "ғ": "г", "қ": "к", "ң": "н", "ө": "о", "ұ": "у", "ү": "у", "һ": "х",
                       "і": "и", "Ә": "а", "Ғ": "г", "Қ": "к", "Ң": "н", "Ө": "о", "Ұ": "у", "Ү": "у",
                       "Һ": "х", "І": "и"})


def fold(s):
    return s.translate(_FOLD)


def _re(p):
    return re.compile(fold(p), re.I)


# слова-объекты → то, что понимает ядро
