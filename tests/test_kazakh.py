@pytest.mark.parametrize("phrase", ["открой ютуб", "таймер на 5 минут", "громче", "найди рецепт борща",
                                    "какая погода", "выключи компьютер", "привет"])
def test_russian_commands_untouched(phrase):
    """Русские команды не должны проходить через казахские правила."""
    assert kazakh.canon(phrase) is None


def test_verb_is_not_a_number():
    """Раньше «дыбысты көтер» превращалось в «громкость көтер»."""
    assert not (kazakh.canon("дыбысты көтер") or "").startswith("громкость")


