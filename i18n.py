import random

_LANG = {"v": "kk"}
LANGS = ("kk", "ru")


def set_lang(lang):
    _LANG["v"] = lang if lang in LANGS else "kk"


def lang():
    return _LANG["v"]


def t(key, **kw):
    table = TEXT.get(_LANG["v"], TEXT["ru"])
    value = table.get(key)
    if value is None:
        value = TEXT["ru"].get(key, key)
    if isinstance(value, (list, tuple)):
        value = random.choice(value)
    return value.format(**kw) if kw else value


