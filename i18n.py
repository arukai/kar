def lst(key):
    """Список (названия месяцев, дней, порядковых слов)."""
    return LISTS.get(_LANG["v"], LISTS["ru"])[key]


def dur(seconds):
    """Длительность для речи: «1 ч 5 мин 30 сек» / «1 сағ 5 мин 30 сек»."""
    seconds = int(seconds)
    h, rest = divmod(seconds, 3600)
    m, s = divmod(rest, 60)
    names = ("ч", "мин", "сек") if _LANG["v"] == "ru" else ("сағ", "мин", "сек")
    parts = [f"{v} {n}" for v, n in ((h, names[0]), (m, names[1]), (s, names[2])) if v]
    return " ".join(parts) or f"0 {names[2]}"


