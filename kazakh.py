def _weather(before, tomorrow=False):
    city = _city(before)
    city = re.sub(r"(дағы|дегі|тағы|тегі|дагы|деги|тагы|теги)$", "", city).strip()
    base = "погода завтра" if tomorrow else "погода"
    return f"{base} в {city}" if city else base


def _timer(c):
    if re.search(r"ошир|токтат|болдырма|жой|жокка|тазала", c):
        return "отмени таймер"
    d = re.sub(r"\b(таймер\w*|будильник\w*|кой\w*|косш\w*|жаса\w*|кою)\b", " ", c)
    d = _units(d)
    return ("таймер на " + d) if d else "таймер"


_GEN = re.compile(r"(дын|дин|тын|тин|нын|нин|дыц|ты|ти|ды|ди|ны|ни)$")


def obj_gen(app):
    """«Spotify-дың» / «хромның» → «spotify» / «хром»: убрать окончание родительного падежа."""
    w = fold(app.strip())
    stem = _GEN.sub("", w)
    return stem if len(stem) >= 3 else w


def _dative(word):
    """«ютубқа» → «ютуб»: отбросить окончание направления (-қа/-ке/-ға/-ге)."""
    return re.sub(r"(ка|ке|га|ге|к|г)$", "", fold(word))


# --- время для напоминаний: «ертең сағат 9-да» → «завтра в 9» ---
_KK_WEEKDAYS = (("дуйсенб", "понедельник"), ("сейсенб", "вторник"), ("сарсенб", "среду"), ("бейсенб", "четверг"),
                ("жума", "пятницу"), ("сенб", "субботу"), ("жексенб", "воскресенье"))
_KK_MONTHS = (("кантар", "января"), ("акпан", "февраля"), ("наурыз", "марта"), ("сауир", "апреля"),
              ("мамыр", "мая"), ("маусым", "июня"), ("шилде", "июля"), ("тамыз", "августа"),
              ("кыркуйек", "сентября"), ("казан", "октября"), ("караша", "ноября"), ("желтоксан", "декабря"))


def _kk_number(word):
    """Казахское числительное с любым окончанием («тоғызда», «бесте») → число или None."""
    for key, value in sorted(NUMBERS.items(), key=lambda kv: -len(kv[0])):
        if word.startswith(key) and value:
            return value
    return None


def _when_kk(text):
    """Казахские слова времени → русские, которые понимает reminders.parse_when. Остальной текст не трогаем:
    «ертең сағат тоғызда анама қоңырау шалуды» → «завтра в 9 анама қоңырау шалуды»."""
    pairs = list(zip(text.split(), fold(text.lower()).split()))
    out, i = [], 0
    while i < len(pairs):
        orig, f = pairs[i]
        word = None
        if f == "сагат" and i + 1 < len(pairs):
            nxt = pairs[i + 1][1]
            hour = int(re.match(r"\d{1,2}", nxt).group()) if re.match(r"^\d", nxt) else _kk_number(nxt)
            if re.match(r"^\d{1,2}:\d{2}", nxt):
                out.append("в " + re.match(r"^\d{1,2}:\d{2}", nxt).group(0))
                i += 2
                continue
            if hour is not None:
                used = 2
                if hour in (10, 20) and i + 2 < len(pairs):  # «он екі» = 12, «жиырма үш» = 23
                    unit = _kk_number(pairs[i + 2][1])
                    if unit is not None and 0 < unit < 10:
                        hour, used = hour + unit, 3
                out.append(f"в {hour}")
                i += used
                continue
        if f.startswith(("берсигуни", "бурсигуни")):
            word = "послезавтра"
        elif f.startswith("ертен") and not f.startswith("ертенги"):
            word = "завтра"
        elif f.startswith("бугин"):
            word = "сегодня"
        elif f.startswith("тангертен"):
            word = "утром"
        elif f.startswith(("кешке", "кешкурын")):
            word = "вечером"
        elif f.startswith(("тусте", "туски")):
            word = "днем"
        elif f.startswith(("тунде", "туни")):
            word = "ночью"
        else:
            for stem, ru in _KK_WEEKDAYS:
                if f.startswith(stem):
                    word = "в " + ru
            for stem, ru in _KK_MONTHS:
                if f.startswith(stem):
                    word = ru
        out.append(word or orig)
        i += 1
    r = " ".join(out)
    r = re.sub(r"(\d+)\s*(?:минут|мин)\w*\s+(?:кейин|кейін|соң|сон)", r"через \1 минут", r)
    r = re.sub(r"(\d+)\s*(?:сагат|сағат)\w*\s+(?:кейин|кейін|соң|сон)", r"через \1 час", r)
    r = re.sub(r"(\d+)\s*секунд\w*\s+(?:кейин|кейін|соң|сон)", r"через \1 секунд", r)
    return re.sub(r"\s+", " ", r).strip()


def _open(t):
    raw = fold(t.strip())
    folder = re.match(r"^(?P<n>.+?)\s+папка\w*$", raw)
    if folder:
        name = folder.group("n")
        mapped = WORDS.get(name)
        return "открой " + mapped if mapped else "открой папку " + name
    drive = re.match(r"^(?P<l>\S+)\s+диск\w*$", raw)
    if drive:
        return "открой диск " + drive.group("l")
    return "открой " + obj(t)


_RU_START = re.compile(r"^(открой|закрой|найди|поищи|ищи|включи|выключи|запусти|поставь|покажи|скажи|нажми|напиши|"
                       r"создай|сделай|какая|какой|какое|что|сколько|громкость|яркость|таймер|погода|пауза|громче|"
                       r"тише|ярче|темнее|прокрути|сверни|заблокируй|проверь|запомни|забудь|отмени|перезагрузи|"
                       r"переключи|следующий|предыдущий|продолжи|перемотай|загугли|погугли|заверши|убей|"
                       r"перейди|зайди|спрячься|выход|стоп)\b")


def _prep(text):
    """Две строки одной длины: оригинал (с казахскими буквами) и свёрнутая копия для поиска правил."""
    o = text.lower().replace("ё", "е").replace("-", "")
    o = "".join(ch if (ch.isalnum() or ch in "_.:/") else " " for ch in o).strip()
    return o, fold(o)


def g(m, o, name):
    """Кусок фразы с оригинальными буквами: запрос «қазақ тілі» не должен превращаться в «казак тили»."""
    return o[m.start(name):m.end(name)].strip()


def _strip_prefix(q):
    f = fold(q)
    m = _SEARCH_PREFIX.match(f + " ")
    return q[m.end():].strip() if m and m.end() <= len(q) else q.strip()


def canon(text):
    """Казахская фраза → каноническая русская команда, или None, если фраза не казахская/не опознана."""
    o, c = _prep(text)
    if not c or _RU_START.match(c):
        return None
    for rx, build in RULES:
        m = rx.search(c)
        if m:
            try:
                out = build(m, c, o)
            except Exception:
                continue
            if out:
                return re.sub(r"\s+", " ", out).strip()
    return None
