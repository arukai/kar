_UNITS = ((re.compile(r"жарты\s+минут\w*"), "полминуты"), (re.compile(r"\bсагат\w*"), "час"),
          (re.compile(r"\bминут\w*"), "минут"), (re.compile(r"\bсекунд\w*"), "секунд"))


def _units(d):
    d = fold(d)
    for rx, repl in _UNITS:
        d = rx.sub(repl, d)
    return d.strip()


def _city(text):
    """Из «Алматыдағы бүгінгі» оставить название города (с оригинальными буквами)."""
    skip = r"^(бугин|казир|ертен|кандай|корсет|айт|тур|гугл|google|яндекс|интернет|галамтор|изде|тап)"
    words = [w for w in text.split() if not re.match(skip, fold(w))]
    return " ".join(words).strip()


